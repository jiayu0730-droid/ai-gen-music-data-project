from __future__ import annotations

"""Build a song-level pre-release score table for the 50 GoldenAI tracks.

Inputs (auto-detected under PROJECT_ROOT/data):
- songs.csv or data/songs/songs.csv
- a market score CSV such as:
  - subgenre_opportunity_score.csv
  - genre_signal_opportunity_score.csv
  - market_gap_opportunity_score.csv
  - data/market/market_opportunity_scores.csv

Outputs:
- data/song_scores.csv
- data/song_score_unmatched.csv
- reports/song_score_summary.md

This script does not invent lyric/audio scores. It creates a provisional
pre-release score from market opportunity + metadata completeness only.
"""

from dataclasses import dataclass
from pathlib import Path
from typing import Iterable
import re

import numpy as np
import pandas as pd


# -----------------------------------------------------------------------------
# Project paths
# -----------------------------------------------------------------------------

def find_project_root(start: Path) -> Path:
    """Walk upward until a folder containing data/ is found."""
    for candidate in [start, *start.parents]:
        if (candidate / "data").exists():
            return candidate
    # Expected location: PROJECT/src/src_final/src_final/04_prepare_song_scores.py
    return start.parents[3]


SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = find_project_root(SCRIPT_DIR)
DATA_DIR = PROJECT_ROOT / "data"
REPORTS_DIR = PROJECT_ROOT / "reports"

OUTPUT_FILE = DATA_DIR / "song_scores.csv"
UNMATCHED_FILE = DATA_DIR / "song_score_unmatched.csv"
SUMMARY_FILE = REPORTS_DIR / "song_score_summary.md"


# -----------------------------------------------------------------------------
# Configuration
# -----------------------------------------------------------------------------

# This is a provisional pre-release score because DistroKid/Spotify performance
# data is not available yet.
MARKET_WEIGHT = 0.85
METADATA_WEIGHT = 0.15

HIGH_THRESHOLD = 80.0
MID_THRESHOLD = 65.0

SONG_FILE_CANDIDATES = [
    DATA_DIR / "songs.csv",
    DATA_DIR / "songs" / "songs.csv",
    DATA_DIR / "suno_generation_plan.csv",
]

MARKET_FILE_CANDIDATES = [
    DATA_DIR / "subgenre_opportunity_score.csv",
    DATA_DIR / "subgenre_opportunity_scores.csv",
    DATA_DIR / "genre_signal_opportunity_score.csv",
    DATA_DIR / "market_gap_opportunity_score.csv",
    DATA_DIR / "genre_signal_score.csv",
    DATA_DIR / "market" / "market_opportunity_scores.csv",
]


